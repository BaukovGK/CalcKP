/**
 * Ошибки стора расчёта, которые разбирают экраны.
 *
 * Отдельным модулем, а не рядом со стором: экранные тесты подменяют стор
 * целиком, и класс, объявленный в нём, пропал бы вместе с ним.
 *
 * @module stores/calc-errors
 */

/**
 * Опросный лист сохранён, а расчёт по нему не пересобран: справочники или
 * шаблоны изделий не загрузились (План_устранения, 1.4).
 *
 * Собирать дерево в такой момент нельзя — встроенным шаблоном вместо
 * действующего оно ушло бы в базу молча. Расчёт пересоберётся при следующей
 * правке листа или открытии расчёта: ревизия ОЛ выросла, а ревизия дерева —
 * нет.
 */
export class CalcDeferredError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'CalcDeferredError'
  }
}
