/**
 * Опознание узла расчёта между сборками — для переноса ручных правок
 * (`stores/calcTree.ts`, reconcileTrees; План_устранения, 1.1).
 *
 * Название узла для этого не годится: в нём параметры ОЛ — «Нитка напорного
 * трубопровода DN150 ×2», «Шахта обслуживания Ø1200 h2300». Сменилось число
 * напорных — сменилось и название, и правки узла пропадали молча. Поэтому у
 * узла есть ключ `slot`, не зависящий от ОЛ: его ставит материализация
 * (`engines/template-def.ts`, materializeRef). Для деревьев, собранных до
 * ключей, остаётся название — сначала целиком, потом его основа без
 * параметров.
 */

/**
 * Основа названия узла — без параметров ОЛ: DN, Ø, h, ×N и пометки
 * материала патрубка.
 *
 * ```
 * titleStem('Нитка напорного трубопровода DN150 ×2')     // 'Нитка напорного трубопровода'
 * titleStem('Патрубок подводящий стеклопластиковый DN250 ×1') // 'Патрубок подводящий'
 * ```
 */
export function titleStem(title: string): string {
  return title
    .replace(/\s+стеклопластиковый/g, '')
    .replace(/\s*(?:DN|Ø|h|×)\s*\d[\d.,]*/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}
