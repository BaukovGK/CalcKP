import { describe, expect, it } from 'vitest'
// Прямой импорт файла из бэкенда: тип-конфиг фронта браузерный, node:fs в нём
// нет, а тянуть его сюда ради одного теста значит ослабить проверки всего src.
// В сборку приложения файл не попадает — он виден только этому тесту.
import lists from '../../../backend/prisma/seed-data/lists.json'
import { CATEGORIES, NON_PURCHASE_CATEGORIES } from './types'

/**
 * Списки категорий и ЕИ — не украшение, а часть ключа поиска цены
 * (`категория|наименование|ЕИ`). Расхождение с мастер-книгой не падает и не
 * подсвечивается: строка просто перестаёт находить цену и молча занижает итог.
 *
 * Эталон — `backend/prisma/seed-data/lists.json`, который пишет экстрактор
 * (`backend/tools/extract-refs.ts`) прямо из листа «НН». До этого теста файл
 * не читал никто: экстрактор его создавал, а код держал те же значения
 * отдельной константой — то есть дрейф был вопросом времени.
 */

describe('константы движка против извлечения из мастер-книги', () => {
  it('категории совпадают с листом «НН» — и по составу, и по порядку', () => {
    expect([...CATEGORIES]).toEqual(lists.categories)
  })

  it('непокупные категории совпадают', () => {
    // Они определяют, что не попадает в Заявку на закупку (ТЗ §9.6).
    expect([...NON_PURCHASE_CATEGORIES]).toEqual(lists.nonPurchaseCategories)
  })

  it('в извлечении ровно шесть единиц измерения', () => {
    // ЕИ — третья часть ключа цены. Список нужен, чтобы заметить появление
    // новой ЕИ в прайсе: она не найдётся ни одной строкой шаблона.
    expect(lists.units).toEqual(['шт', 'м', 'кг', 'чел. ч', 'м²', 'руб/м'])
  })

  it('непокупные категории — подмножество общего списка', () => {
    for (const c of NON_PURCHASE_CATEGORIES) expect(CATEGORIES).toContain(c)
  })
})
