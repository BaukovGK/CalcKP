/**
 * Типы движка расчёта (§9 ТЗ, Механика §5–§6, Библиотека §1).
 *
 * Модель намеренно отделена от текущих UI-типов (`types/calculator.ts`,
 * свободное дерево связка→группа→подгруппа→строка): целевая структура —
 * материализованное дерево «Сборка→Компонент→Строка», и движок обязан быть
 * чистым от Vue/Pinia, чтобы оставаться тестируемым.
 */

/** Тип строки расчёта (Библиотека §1.1). */
export type RowKind =
  /** Закупаемая позиция: категория, наименование, ЕИ, цена из прайса. */
  | 'МАТЕРИАЛ'
  /** Собственное производство: масса/объём, ставка ₽/кг; порождает ФОТ. */
  | 'ОПЕРАЦИЯ'
  /** Производная строка операции. Независимый ввод запрещён, override возможен. */
  | 'ФОТ'

/**
 * 16 категорий строки (лист «Списки», AG2:AG17).
 * Порядок значим: последние три — непокупные (см. NON_PURCHASE_CATEGORIES).
 */
export const CATEGORIES = [
  'Грузоподъем',
  'Выключатели',
  'Детали труб_да ПЭ ПВХ PPR',
  'Детали трубопровода сталь',
  'Запорная арматура',
  'Металлопрокат',
  'Метизы',
  'Прочее оборудование',
  'Насосы, АТМ',
  'Датчики',
  'Расходомеры',
  'Шкафы',
  'Прочие материалы',
  'Собственное производство',
  'Работы',
  'ФОТ',
] as const

export type Category = (typeof CATEGORIES)[number]

/**
 * Непокупные категории. Эталон: `F = IF(OR(C = Списки!$AG$15:$AG$17); "нет"; "да")`
 * — то есть «Закупка = да» для всех, кроме этих трёх (Механика §5.3).
 */
export const NON_PURCHASE_CATEGORIES: readonly Category[] = [
  'Собственное производство',
  'Работы',
  'ФОТ',
]

/** ЕИ, определяющая физический смысл строки (Механика §5.3). */
export const UNIT_MASS = 'кг' // формовка/ламинат: участвует в массе формовки и ацетоне
export const UNIT_HOURS = 'чел. ч' // труд: участвует в часах и накладных

/**
 * Строка расчёта. Два независимых канала — количество и цена (Механика §5).
 *
 * Инвариант: `qtyCalc` никогда не редактируется и не теряется — сброс override
 * возвращает расчётное значение.
 */
export interface EngineRow {
  id: string
  kind: RowKind
  category: Category
  name: string
  unit: string

  /** Количество по формуле шаблона. `null` — строка добавлена вручную. */
  qtyCalc: number | null
  /** Ручной override количества. Хранится ВЫРАЖЕНИЕМ (Механика §5.1). */
  qtyManual: string | null

  /** Цена из прайса по тройке (категория, наименование, ЕИ). */
  priceCatalog: number | null
  /** Ручной override цены. */
  priceManual: number | null

  /**
   * Коэффициент ФОТ для строки-спутника. Задаётся узлом каталога явно
   * (особые ламинирования с k = 1.0); эвристика по подстроке — лишь дефолт
   * (Механика §6).
   */
  fotK?: number
  /** Для ФОТ-спутника — id родительской операции. */
  parentId?: string

  /** Выключенная строка: qty = 0, в итог не входит (Механика §7.2). */
  enabled?: boolean

  note?: string
}

/** Результат вычисления строки. */
export interface RowResult {
  /** Итоговое количество с учётом флагов и тиража. */
  qty: number
  /** Применённая цена: `priceManual ?? priceCatalog`. */
  price: number | null
  /** `qty × price`; для строки без цены — 0. */
  sum: number
  /** Нет ни каталожной, ни ручной цены — строка «красная» (Механика §5.2). */
  missingPrice: boolean
  /** Количество взято из ручного override. */
  qtyOverridden: boolean
  /** Цена взята из ручного override. */
  priceOverridden: boolean
}
