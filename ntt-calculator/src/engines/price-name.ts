/**
 * Нормализация наименований прайса — копия `backend/src/utils/price-name.ts`.
 *
 * Бэкенд приводит наименования при импорте и в базе; здесь те же правила
 * нужны, чтобы сопоставлять строки расчёта между пересборками: у деревьев,
 * собранных до чистки прайса, в наименованиях остались двойные и
 * неразрывные пробелы, латиница вместо кириллицы, а свежая материализация
 * даёт уже приведённые. Без приведения ручные правки таких строк при
 * первой же правке ОЛ терялись бы.
 *
 * Общего пакета у фронта и бэка нет, поэтому код повторён, а совпадение
 * держат общие примеры `backend/src/utils/price-name.vectors.json` — их
 * прогоняют тесты обеих сторон.
 */

/** Символы нулевой ширины: при копировании из PDF они приезжают внутрь слов. */
const ZERO_WIDTH = /[\u200b-\u200d\u2060]/g

/**
 * Любые пробельные символы (NBSP, тонкий, табуляция…) — в обычный пробел,
 * серии — в один, по краям — прочь. Для категорий и ЕИ этого достаточно.
 */
export function normalizePriceText(s: string): string {
  return s.replace(ZERO_WIDTH, '').replace(/\s+/g, ' ').trim()
}

/**
 * Наименование позиции прайса в каноническом виде.
 *
 * Идемпотентна: повторный вызов ничего не меняет — на этом держится миграция
 * базы (строка в каноническом виде не может столкнуться с другой строкой,
 * которую ещё предстоит привести).
 */
export function normalizePriceName(s: string): string {
  return (
    normalizePriceText(s)
      // «ГОСТ» с латинскими O, C, T — самая частая подмена (5 позиций «Круг»).
      .replace(/Г[OО][CС][TТ]/g, 'ГОСТ')
      // Размеры через латинскую x: «108x8» → «108х8», как во всём прайсе.
      .replace(/(\d)x(?=\d)/g, '$1х')
      // Миллиампер с латинской A.
      .replace(/мA(?![A-Za-zА-Яа-яЁё])/g, 'мА')
      // Резьба «M12» латиницей — в прайсе везде «М12» кириллицей.
      .replace(/(^|[^A-Za-z])M(?=\d)/g, '$1М')
      // Поле допуска гайки «7H» после размера резьбы — в прайсе «7Н».
      .replace(/([МM]\d+(?:[.,]\d+)?-\d)H/g, '$1Н')
      // «ɡ» (U+0261, латинская рукописная) на месте обычной g в «6g».
      .replace(/\u0261/g, 'g')
  )
}
