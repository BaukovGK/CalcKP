/**
 * Ряды допустимых DN — чтобы в поле диаметра не оставалось чисел, которых
 * нет в природе.
 *
 * Раньше DN патрубка вводился свободным числом: «2850» принималось как есть,
 * уходило в наименования строк («Задвижка … DN2850») и давало строки, для
 * которых в прайсе нет и не может быть цены.
 */

import { tryEvalExpr } from './expr'

/**
 * DN патрубков — ряд мастер-книги («Шаблон 3.0.xlsx», лист «Списки», столбец
 * Y «DN подвод патрубка»). С ним же сходится прайс: задвижки и обратные
 * клапаны в нём есть ровно на DN 50, 65, 80, 100, 150, 200, 250, 300 — DN125,
 * которого нет в ряду, нет и в прайсе.
 */
export const NOZZLE_DN_SERIES: readonly number[] = [
  50, 65, 80, 100, 150, 200, 250, 300, 350, 400, 450, 500, 550, 600, 650, 700, 750, 800, 850, 900, 950,
  1000, 1100, 1200, 1300, 1400, 1500, 1600,
]

/**
 * Ближайшее значение ряда.
 *
 * Ближайшее, а не следующее вверх: в поле DN часто вводят наружный диаметр
 * трубы — 315, 160, 110 у ПЭ, — и ему соответствует DN 300, 150, 100, а не
 * следующий размер. При равном удалении берётся больший: меньший патрубок
 * мог бы не пропустить трубу. Вне ряда — его край.
 */
/**
 * Ввод поля DN → принятое значение ряда.
 *
 * Выражения разбираются так же, как в других числовых полях («2*100» → 200).
 * Пустое и неразобранное не трогается: пустое — законное «не задано», а
 * неразобранное уже подсвечено правилом числовых полей.
 *
 * @returns текст для поля и исходное число, если его пришлось заменить
 *          (`from` — для сообщения «2850 нет в ряду — принят 1600»)
 */
export function acceptDn(
  raw: string,
  series: readonly number[] = NOZZLE_DN_SERIES,
): { text: string; from: number | null } | null {
  const value = tryEvalExpr(raw)
  if (value == null) return null
  const dn = snapToSeries(value, series)
  return { text: String(dn), from: dn !== value ? value : null }
}

export function snapToSeries(value: number, series: readonly number[]): number {
  if (series.length === 0) throw new Error('Пустой ряд')
  let best = series[0]!
  for (const s of series) {
    const d = Math.abs(s - value)
    const bestD = Math.abs(best - value)
    if (d < bestD || (d === bestD && s > best)) best = s
  }
  return best
}
