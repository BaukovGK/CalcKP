/**
 * Опросный лист КНС: авторасчёты (§5.6 ТЗ, прототип «Опросный лист v2»).
 *
 * КНС, ЛНС и ДНС конструктивно идентичны — один шаблон; «Тип НС» влияет на
 * подписи и входы, не на структуру (Реверс §1).
 *
 * Все функции чистые: вход — параметры ОЛ, выход — значения. Никакого Vue.
 */

import { roundUp } from './rounding'
import { tryEvalExpr } from './expr'

// ─── Константы подбора глубины (Механика §13, прототип ОЛ) ──────────────────

/** Пусков насоса в час — норматив подбора эффективного объёма. */
export const STARTS_PER_HOUR = 10
/** Минимальное время между пусками, мин. */
export const MIN_CYCLE_MINUTES = 5
/** Технологический запас над рабочим уровнем, м. */
export const FREEBOARD_M = 0.3
/** Высота рамы, м (по умолчанию; в ТЗ §5.6 — поле ОЛ). */
export const DEFAULT_FRAME_H_M = 0.16
/** Минимальный уровень жидкости насоса, м (по умолчанию; поле ОЛ). */
export const DEFAULT_MIN_LEVEL_M = 0.627

/** Единицы измерения притока (прототип: переключатель с конвертацией). */
export type FlowUnit = 'l/s' | 'm3/h' | 'm3/day'

/** Приток к л/с. */
export function toLps(value: number, unit: FlowUnit): number {
  switch (unit) {
    case 'l/s':
      return value
    case 'm3/h':
      return value / 3.6
    case 'm3/day':
      return value / 86.4
  }
}

/** Приток из л/с в указанную ЕИ (для переключателя в UI). */
export function fromLps(lps: number, unit: FlowUnit): number {
  switch (unit) {
    case 'l/s':
      return lps
    case 'm3/h':
      return lps * 3.6
    case 'm3/day':
      return lps * 86.4
  }
}

/**
 * Значение поля расхода при смене единиц — то же количество воды в новых
 * единицах: 25,13 л/с → 90,47 м³/ч.
 *
 * Раньше менялась только подпись: 25,13 л/с становились 25,13 м³/ч, то есть
 * в 3,6 раза меньше, а вслед за расходом молча уезжали подбор насоса, глубина
 * и гидравлика напорного.
 *
 * Два знака после запятой: при переключении туда и обратно значение
 * возвращается к исходному (90,47 м³/ч → 25,13 л/с).
 *
 * @returns новый текст поля; `null` — пересчитывать нечего (пусто, не число,
 *          единицы те же)
 */
export function convertFlowText(raw: string, from: FlowUnit, to: FlowUnit): string | null {
  if (from === to) return null
  const value = tryEvalExpr(raw)
  if (value == null) return null
  return formatFlow(fromLps(toLps(value, from), to))
}

/** Расход в поле ОЛ: два знака, запятая, без пробелов-разрядов — как вводят руками. */
export function formatFlow(value: number): string {
  return value.toLocaleString('ru-RU', { maximumFractionDigits: 2, useGrouping: false })
}

export interface DepthInput {
  /** Максимальный приток. */
  flow: number
  flowUnit: FlowUnit
  /** DN корпуса, мм. */
  dn: number
  /** Количество рабочих насосов. */
  pumpsWorking: number
  /** Глубина залегания лотка подводящего патрубка, мм. */
  inletInvertMm: number | null
  /** Высота рамы, м. */
  frameHm?: number
  /** Минимальный уровень жидкости насоса, м. */
  minLevelM?: number
}

export interface DepthResult {
  /** Приток, приведённый к л/с. */
  qLps: number
  /** Эффективный объём, м³. */
  vEf: number
  /** Минимальный объём, м³. */
  vMin: number
  /** Рабочая высота, м. */
  hRab: number
  /** Суммарная расчётная высота, м. */
  hR: number
  /** Глубина подземной части, мм. `null`, если не задан лоток. */
  npodzMm: number | null
}

/**
 * Подбор глубины подземной части (фирменная механика ОЛ, live-панель).
 *
 * ```
 * Vэф   = Q·3,6 / (4 · пусков_в_час · n)
 * Vмин  = (Q·3,6 / n) · 5/60
 * hраб  = 4·Vмин / (π·(DN/1000)²)
 * hР    = hраб + 0,3 + h_рамы + h_мин
 * Нподз = ROUNDUP((лоток/1000 + hР)·1000; −2)      ← вверх до 100 мм
 * ```
 *
 * Контроль (ОЛ3487, прототип): Q 25,13 л/с · DN 3000 · n 2 · лоток 9910 мм
 * → Vэф 1,13 · Vмин 3,77 · hраб 0,533 · hР 1,620 · **Нподз 11 600 мм**.
 *
 * ⚠️ `hраб` считается от **Vмин**, а не от «Vраб», как записано в ТЗ §5.6:
 * только так воспроизводится контрольное число прототипа.
 */
export function computeDepth(input: DepthInput): DepthResult {
  const {
    flow,
    flowUnit,
    dn,
    pumpsWorking,
    inletInvertMm,
    frameHm = DEFAULT_FRAME_H_M,
    minLevelM = DEFAULT_MIN_LEVEL_M,
  } = input

  const qLps = toLps(flow, flowUnit)
  const n = pumpsWorking > 0 ? pumpsWorking : 1

  const vEf = (qLps * 3.6) / (4 * STARTS_PER_HOUR * n)
  const vMin = ((qLps * 3.6) / n) * (MIN_CYCLE_MINUTES / 60)
  const hRab = dn > 0 ? (4 * vMin) / (Math.PI * (dn / 1000) ** 2) : 0
  const hR = hRab + FREEBOARD_M + frameHm + minLevelM

  const npodzMm = inletInvertMm == null ? null : roundUp((inletInvertMm / 1000 + hR) * 1000, -2)

  return { qLps, vEf, vMin, hRab, hR, npodzMm }
}

// ─── PN / SN ─────────────────────────────────────────────────────────────────

/** PN опросного листа: корпус КНС безнапорный (README хендоффа, эталон G8). */
export const PN_SURVEY_DEFAULT = 0.1

/**
 * Реальные ступени кольцевой жёсткости корпуса. Их всего две: производство
 * делает трубу SN 5000 либо SN 10000. Обозначения 8000 и 12000 — то же изделие
 * с двумя дополнительными нитками ровинга, см. {@link snDesignation}.
 */
export const SN_BASE = { normal: 5000, raised: 10000 } as const

/** Порог глубины, мм: выше него — SN 10000. */
export const SN_DEPTH_THRESHOLD_MM = 7000

/**
 * Реальная кольцевая жёсткость корпуса по глубине.
 *
 * `глубина > 7000 мм → 10000 · иначе 5000`
 *
 * Флаг «под проезжей частью» поднимает жёсткость на ступень (5000 → 10000):
 * помимо этого он требует разгрузочной плиты, дорожного люка и особых
 * требований к обратной засыпке — это состав спецификации, а не жёсткость.
 *
 * Возвращает именно РАСЧЁТНУЮ жёсткость: от неё зависят вес трубы в справочнике
 * и трудоёмкость. Обозначение для заказчика по ТТ МВК берётся отдельно
 * ({@link snDesignation}) — так реальный ОЛ3487 и показывает SN 10000 при
 * действующих ТТ МВК.
 *
 * Подбор предварительный: окончательная жёсткость подтверждается расчётом
 * прочности (его делает отдельная программа).
 *
 * То же правило — на сервере (`backend/src/utils/ring-stiffness.ts`,
 * `POST /api/pump-station/ring-stiffness`): общего пакета нет, совпадение
 * держат общие примеры `backend/src/utils/sn-rule.vectors.json`.
 */
export function snByDepth(depthMm: number, opts: { underRoadway?: boolean } = {}): number {
  return depthMm > SN_DEPTH_THRESHOLD_MM || opts.underRoadway ? SN_BASE.raised : SN_BASE.normal
}

/** Обозначения жёсткости по ТТ МВК: та же труба плюс две нитки ровинга. */
const SN_MVK_LABEL: Record<number, number> = { 5000: 8000, 10000: 12000 }

/**
 * Обозначение жёсткости для заказчика.
 *
 * По требованиям МВК труба маркируется как 8000 или 12000 — конструктивно это
 * SN 5000 и 10000 с двумя дополнительными нитками ровинга, по массе и габаритам
 * изделия одинаковы. Поэтому обозначение влияет только на марку в документах,
 * а вес и трудоёмкость считаются по реальной жёсткости.
 */
export function snDesignation(sn: number, opts: { mvk?: boolean } = {}): number {
  return opts.mvk ? (SN_MVK_LABEL[sn] ?? sn) : sn
}

/**
 * Автоподбор PN ТРУБЫ для поиска веса (эталон, ячейка `F7`).
 *
 * ⚠️ Это НЕ `PN_ОЛ`: в расчёте участвуют две разные PN (ТЗ §9.4).
 * `PN_ОЛ` (0,1 — безнапорный корпус) идёт только в НАИМЕНОВАНИЕ трубы;
 * `PN_трубы` — только в КЛЮЧ ПОИСКА ВЕСА.
 *
 * ```
 * F7 = IF(PN_ОЛ > 0,6 И (DN;SN) ∈ {(1200;2500), (1200;10000), (1300;2500)}; 1,6;
 *      IF(DN = 1300 И SN ∈ {5000, 10000} И PN_ОЛ ≤ 0,4;                      0,4;
 *      IF(PN_ОЛ ≤ 0,6;                                                        0,6;
 *                                                                             1)))
 * ```
 *
 * ❗ Ветка `0,4` эталона ведёт в НЕСУЩЕСТВУЮЩИЙ ключ таблицы весов, и она
 * достижима на реальном кейсе: у КНС `PN_ОЛ` = 0,1, поэтому при DN 1300
 * глубже 5 м (SN 5000) поиск веса промахивался — ровно как и в самом Excel.
 *
 * **Закрыто ответом завода (2026-09-09).** Труба PN 0,1, 0,4 и 0,6 — это ОДНА
 * И ТА ЖЕ труба, так обусловлено технологией производства, и ссылка идёт на
 * PN 0,6; значит и вес погонного метра у них общий. Само число 0,4 — класс
 * ИЗДЕЛИЯ: такие ёмкости безнапорные, и 0,4 у них принимается независимо от
 * того, из какой трубы они изготовлены. Поэтому ветка убрана: оба класса
 * разрешаются в 0,6, и DN1300 глубже 5 м находит вес вместо «красной» строки.
 *
 * ⚠️ Это касается только ВЕСА. Ламинация, наоборот, считается минимально
 * возможная — по нижнему классу справочника Мс (`jointLayerIndex` в
 * `stores/calcTree.ts`; таблица в атмосферах, нижняя строка 4 атм = 0,4 МПа).
 * Две величины расходятся намеренно.
 *
 * Ветка `1,6` остаётся невоспроизводимой: она требует `PN_ОЛ > 0,6`, у КНС
 * недостижима, а ключи (1200;1,6) и (1300;1,6) в таблице отсутствуют —
 * `doc/Вопросы_заводу.md` §2б.
 */
export function pnForWeightLookup(pnSurvey: number, dn: number, sn: number): number {
  const specialFor16 = [
    [1200, 2500],
    [1200, 10000],
    [1300, 2500],
  ]
  if (pnSurvey > 0.6 && specialFor16.some(([d, s]) => d === dn && s === sn)) return 1.6
  // Ветки эталона «→ 0,4» здесь нет намеренно: труба PN 0,1, 0,4 и 0,6 —
  // одна и та же по технологии производства, ссылка идёт на 0,6, и следующая
  // строка накрывает все три. Возвращать 0,4, как делает лист, значит искать
  // несуществующий ключ.
  if (pnSurvey <= 0.6) return 0.6
  return 1
}

/**
 * Марка трубы корпуса: `Труба СК/НПС-К {DN}-{PN_ОЛ}-{SN}` (Механика §5.3).
 *
 * В марку идёт ОБОЗНАЧЕНИЕ жёсткости: под ТТ МВК заказчик видит 8000/12000
 * вместо расчётных 5000/10000 ({@link snDesignation}). Вес и трудоёмкость при
 * этом считаются по расчётной жёсткости — изделие то же.
 */
export function pipeGradeName(
  dn: number,
  pnSurvey: number,
  sn: number,
  opts: { mvk?: boolean } = {},
): string {
  const pn = pnSurvey.toLocaleString('ru-RU')
  return `Труба СК/НПС-К ${dn}-${pn}-${snDesignation(sn, opts)}`
}

// ─── Гильзы ──────────────────────────────────────────────────────────────────

/**
 * Диаметр гильзы для прохода патрубка (эталон `K8`/`M8`):
 * `IF(DN ≥ 200; CEILING(DN+100; 100); CEILING(DN+100; 50))`.
 *
 * Тонкость первоисточника: при `DN < 100` надбавка +100 НЕ применяется.
 */
export function sleeveDiameter(nozzleDn: number): number {
  const base = nozzleDn < 100 ? nozzleDn : nozzleDn + 100
  const step = nozzleDn >= 200 ? 100 : 50
  return Math.ceil(base / step) * step
}

// ─── Арматура ────────────────────────────────────────────────────────────────

/**
 * Кол-во задвижек на подводящих (безнапорных) трубопроводах.
 *
 * `= кол-во подводящих патрубков × флаг «арматура на подводящем»`.
 * Задвижки ставятся только на безнапорные подводящие (README хендоффа).
 */
export function gateValveCount(inletCount: number, valveOnInlet: boolean): number {
  return valveOnInlet ? inletCount : 0
}

/**
 * Кол-во задвижек на напорной стороне, без аварийной линии.
 *
 * ```
 * = (раб + рез) на стояках + отводящих патрубков
 * ```
 *
 * По принципиальной схеме завода задвижка стоит на стояке КАЖДОГО насоса —
 * включая резервный: он физически установлен и обвязан так же, как рабочий.
 * Поэтому здесь считаются все насосы станции, а не только рабочие; рабочие
 * определяют РАСХОД (гидравлика, `pipe-hydraulics.ts`), а установленные —
 * СОСТАВ. Плюс по задвижке на каждый отводящий патрубок.
 *
 * Аварийная линия сюда не входит: её задвижка и обратный клапан
 * материализуются вместе с ней, в разделе 5 под флагом ОЛ, — чтобы каждая
 * позиция считалась ровно в одном месте.
 *
 * Контроль (ОЛ3487): 3 насоса + 2 отводящих = 5, плюс задвижка на подводящем
 * и аварийная — итого 7, ровно как в опросном листе («Количество задвижек»).
 */
export function pressureGateValveCount(
  pumpsWorking: number,
  pumpsReserve: number,
  outletCount: number,
): number {
  return pumpsWorking + pumpsReserve + outletCount
}

/**
 * Кол-во обратных клапанов на стояках насосов, без аварийной линии.
 *
 * `= раб + рез` — по клапану на каждый установленный насос (схема завода).
 * Клапан аварийной линии идёт вместе с ней, в разделе 5.
 */
export function checkValveCount(pumpsWorking: number, pumpsReserve: number): number {
  return pumpsWorking + pumpsReserve
}

/** Кол-во поплавковых выключателей: `раб + рез + 2` (Механика §7.2). */
export function floatSwitchCount(pumpsWorking: number, pumpsReserve: number): number {
  return pumpsWorking + pumpsReserve + 2
}
