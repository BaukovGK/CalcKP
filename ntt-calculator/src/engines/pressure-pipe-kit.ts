/**
 * Быстросъёмные (пожарные) гайки аварийного трубопровода.
 *
 * Размер гайки НЕ следует за диаметром напорного: сам аварийный трубопровод
 * идёт тем же DN, а гайка бывает разной — от неё зависит, чем подключится
 * ассенизационная машина. Разброс цены восьмикратный (250…2000 ₽), поэтому
 * размер вынесен в опросный лист, а не выведен формулой.
 *
 * В листе позиция названа «РОТ-ГАЙКА ГМ150», в прайсе — «Гайка пожарная
 * ГМ150»; ключ поиска цены прайсовый, иначе строка выпускалась бы «красной».
 */
export const HOSE_NUT_SIZES: readonly number[] = [50, 80, 100, 125, 150]

/** Размер по умолчанию — тот, что стоит в эталонном ОЛ3487. */
export const DEFAULT_HOSE_NUT_GM = 150

/** Позиция гайки по размеру ГМ. */
export function hoseNutItem(gm: number): KitItem {
  return { category: 'Прочие материалы', name: `Гайка пожарная ГМ${gm}`, unit: 'шт' }
}

