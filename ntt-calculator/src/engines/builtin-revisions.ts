/** Действующая редакция встроенного шаблона изделия — номер последней записи. */
export function builtinRevision(device: DeviceType): number {
  const list = BUILTIN_REVISIONS[device]
  return list[list.length - 1]!.version
}

/**
 * Редакции новее `from` — что изменилось с тех пор, как собран расчёт. Нет
 * номера (дерево собрано до учёта редакций) — все.
 */
export function revisionsAfter(device: DeviceType, from: number | null | undefined): BuiltinRevision[] {
  return BUILTIN_REVISIONS[device].filter((r) => from == null || r.version > from)
}
