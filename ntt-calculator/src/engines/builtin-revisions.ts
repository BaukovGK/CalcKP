/**
 * Редакции встроенного шаблона изделия — версионирование того, что задано
 * кодом (Библиотека §6.2).
 *
 * Состав расчёта задают два слоя, и у каждого своя версия:
 *  - шаблон технолога (`ProductTemplateVersion`, в дереве
 *    `CalcTree.templateVersion`) — разделы и узлы, опубликованные в
 *    редакторе шаблонов; 0 — встроенный шаблон;
 *  - редакция встроенного шаблона (`CalcTree.builtinRevision`) — код:
 *    формулы и состав встроенных узлов, встроенный шаблон и то, как код
 *    исполняет узлы каталога. Меняется только релизом.
 *
 * Без редакции «встроенный шаблон» в снапшоте КП не говорил, какой код собрал
 * расчёт: релиз правил формулу или состав узла, количества менялись, а версия
 * оставалась та же. Теперь каждый релиз, меняющий то, что код строит из ОЛ,
 * заводит редакцию — номер, дату и что изменилось. Забыть нельзя: отпечаток
 * сборки (builtin-fingerprint.ts) сверяется с отпечатком последней редакции
 * в тесте builtin-revisions.test.ts, и тест падает, если результат изменился,
 * а редакция — нет.
 *
 * Как завести редакцию: добавить запись в конец списка изделия — следующий
 * номер, дату, что изменилось словами инженера (текст видит расчётчик в
 * плашке «шаблон обновился») и новый отпечаток — его печатает упавший тест.
 * Изменились узлы, общие для изделий, — запись у каждого, чей отпечаток
 * изменился.
 */

