/**
 * Состав изделия текстом: что набрали, то и уйдёт в документ.
 *
 * Главное, что держат тесты: состав переживает переключение «таблица ↔ текст»
 * без потерь, дефис внутри наименования не путается с разделителем количества,
 * а строка, которую не удалось разобрать, не теряется.
 */
import { describe, expect, it } from 'vitest'
import { kitToText, textToKit } from './kp-kit-text'

const KIT = [
  { name: 'Стеклокомпозитный корпус «НТТ» GRP, D=3 000 мм', qty: 1, unit: 'шт.' },
  { name: 'Люк стеклокомпозитный с замком натяжным', qty: 1, unit: 'компл.' },
  { name: 'Насос погружной VSL.100.55.4.5.0D (Q=25,13 л/с, H=12,9 м)', qty: 3, unit: 'шт.' },
]

describe('состав текстом', () => {
  it('строка на позицию, количество и единица в конце', () => {
    expect(kitToText(KIT).split('\n')).toEqual([
      'Стеклокомпозитный корпус «НТТ» GRP, D=3 000 мм - 1 шт.',
      'Люк стеклокомпозитный с замком натяжным - 1 компл.',
      'Насос погружной VSL.100.55.4.5.0D (Q=25,13 л/с, H=12,9 м) - 3 шт.',
    ])
  })

  it('переключение «таблица ↔ текст» ничего не теряет', () => {
    expect(textToKit(kitToText(KIT))).toEqual(KIT)
  })

  it('дефис внутри наименования не путается с разделителем', () => {
    expect(textToKit('Задвижка Ду-500 с электроприводом - 2 шт.')).toEqual([
      { name: 'Задвижка Ду-500 с электроприводом', qty: 2, unit: 'шт.' },
    ])
  })

  it('дробное количество — запятой, как в документе', () => {
    expect(kitToText([{ name: 'Кабель', qty: 12.5, unit: 'м' }])).toBe('Кабель - 12,5 м')
    expect(textToKit('Кабель - 12,5 м')).toEqual([{ name: 'Кабель', qty: 12.5, unit: 'м' }])
  })

  it('маркер списка и точка с запятой из документа не мешают', () => {
    // Состав копируют из прошлого КП прямо с оформлением списка.
    expect(textToKit('- Лестница из нержавеющей стали - 1 шт.;')).toEqual([
      { name: 'Лестница из нержавеющей стали', qty: 1, unit: 'шт.' },
    ])
  })

  it('без единицы измерения — штуки; пустые строки пропускаются', () => {
    expect(textToKit('Гильза DN 250 - 2\n\n   \nЛюк - 1 компл.')).toEqual([
      { name: 'Гильза DN 250', qty: 2, unit: 'шт.' },
      { name: 'Люк', qty: 1, unit: 'компл.' },
    ])
  })

  it('неразобранная строка не теряется, а становится наименованием', () => {
    expect(textToKit('Шкаф управления уличного исполнения')).toEqual([
      { name: 'Шкаф управления уличного исполнения', qty: 1, unit: 'шт.' },
    ])
  })

  it('пустой состав в обе стороны', () => {
    expect(kitToText([])).toBe('')
    expect(textToKit('')).toEqual([])
    expect(textToKit('\n  \n')).toEqual([])
  })
})
