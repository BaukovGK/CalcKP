/**
 * Состав изделия текстом: строка на позицию.
 *
 * В таблице каждая позиция — три поля, и наименование узла в своё поле не
 * влезает: «Стеклокомпозитный корпус «НТТ» GRP, D=3 000 мм, Hполная=11 900 мм,
 * …» обрезается на середине, а править вслепую то, что уйдёт заказчику,
 * нельзя. Текстом весь состав виден целиком, строки переставляются и
 * копируются как обычный текст — из письма, из прошлого КП, из чертежа.
 *
 * Формат строки — «Наименование - Кол-во Ед.»: то же, что печатается в
 * документе, только без маркера списка и точки с запятой, чтобы не набирать
 * лишнего. Разбор прощает и их, и пропущенную единицу измерения: строка,
 * которую не удалось прочитать, целиком становится наименованием — потерять
 * набранное хуже, чем показать «1 шт.» там, где человек не дописал количество.
 *
 * @module utils/kp-kit-text
 */

import type { KpKitItem } from '@/api/estimates'

/** Единица измерения по умолчанию — она же у кнопки «+ строка». */
export const DEFAULT_UNIT = 'шт.'

/** Количество для строки: «1», «1,5» — как в документе, запятой. */
function showQty(qty: number): string {
  if (!Number.isFinite(qty)) return '1'
  return Number.isInteger(qty) ? String(qty) : String(qty).replace('.', ',')
}

/** Состав → текст, по строке на позицию. */
export function kitToText(kit: readonly KpKitItem[]): string {
  return kit.map((i) => `${i.name} - ${showQty(i.qty)} ${i.unit}`.trim()).join('\n')
}

/**
 * Текст → состав.
 *
 * Хвост строки читается как «— число единица»: делим по ПОСЛЕДНЕМУ « - »,
 * потому что дефис встречается и в самих наименованиях («Ду-500»).
 */
export function textToKit(text: string): KpKitItem[] {
  const items: KpKitItem[] = []

  for (const raw of text.split('\n')) {
    // Маркер списка и точка с запятой — из документа: их вставляют копированием.
    const line = raw.trim().replace(/^[-–—•]\s+/, '').replace(/;+$/, '').trim()
    if (line === '') continue

    const m = line.match(/^(.*\S)\s+-\s+(\d+(?:[.,]\d+)?)(?:\s+(\S.*))?$/)
    if (m) {
      items.push({
        name: m[1]!.trim(),
        qty: Number(m[2]!.replace(',', '.')),
        unit: (m[3] ?? DEFAULT_UNIT).trim(),
      })
    } else {
      items.push({ name: line, qty: 1, unit: DEFAULT_UNIT })
    }
  }

  return items
}
