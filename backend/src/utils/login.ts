/**
 * Логин — латиницей.
 *
 * То же правило держит экран входа (`ntt-calculator/src/utils/latin-input.ts`):
 * кириллица в поле не печатается. Здесь оно повторено на входе данных, потому
 * что учётная запись с адресом в русской раскладке выглядит настоящей, а войти
 * в неё нельзя — поле логина такой адрес просто не примет. Отказ при создании
 * лучше, чем мёртвая учётная запись.
 *
 * Пароля правило не касается: он может быть любым.
 *
 * @module utils/login
 */

/** Символы логина: латиница, цифры и знаки адреса почты. */
export const LATIN_LOGIN = /^[A-Za-z0-9@._+-]+$/

/** Текст отказа — для схемы и для сообщений. */
export const LATIN_LOGIN_MESSAGE =
  'Email вводится латиницей: адрес в русской раскладке выглядит как настоящий, но войти по нему нельзя'

/** Логин записан латиницей и знаками адреса. */
export function isLatinLogin(email: string): boolean {
  return LATIN_LOGIN.test(email)
}
