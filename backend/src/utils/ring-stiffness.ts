/**
 * Подбор кольцевой жёсткости корпуса (SN, Па) — правило завода.
 *
 * Реальных ступеней две: производство делает трубу SN 5000 либо SN 10000.
 * ```
 * глубина корпуса > 7000 мм  или  «под проезжей частью»  →  SN 10000
 * иначе                                                  →  SN  5000
 * ```
 * Ровно на пороге (7000 мм) — нижняя ступень. Глубина — подземная часть
 * корпуса: Нподз у КНС, полная глубина с горловиной у колодца.
 *
 * Обозначение по ТТ МВК — 8000 вместо 5000 и 12000 вместо 10000 — не другая
 * жёсткость, а та же труба с двумя дополнительными нитками ровинга: по массе
 * и габаритам одинаковая. Поэтому жёсткость и обозначение разведены: вес и
 * трудоёмкость считаются по SN 5000/10000, обозначение идёт только в марку.
 *
 * Правило задано в двух местах: здесь и во фронтенде
 * (`ntt-calculator/src/engines/survey-kns.ts`, `snByDepth` и `snDesignation`)
 * — общего пакета у них нет. Обе реализации проверяются одними примерами,
 * `sn-rule.vectors.json`, и разойтись молча не могут.
 *
 * Прежняя версия модуля (28.07.2026) была старше правила завода: сравнивала
 * с 7 м «глубину подводящего патрубка + 2 м», не знала про проезжую часть и
 * возвращала обозначение МВК вместо жёсткости. Опросный лист перешёл на
 * правило завода 30.07.2026, и два контура с тех пор расходились: у лотка
 * около 5 м сервер давал SN 10000, опросный лист — 5000.
 *
 * Подбор предварительный: окончательную жёсткость подтверждает расчёт
 * прочности (отдельная программа).
 *
 * @module utils/ring-stiffness
 */

/** Реальные ступени кольцевой жёсткости, Па. */
export const SN_BASE = { normal: 5000, raised: 10000 } as const

/** Порог глубины корпуса, мм: выше него — SN 10000. */
export const SN_DEPTH_THRESHOLD_MM = 7000

/** Обозначения жёсткости по ТТ МВК: та же труба плюс две нитки ровинга. */
export const SN_MVK_DESIGNATION: Readonly<Record<number, number>> = { 5000: 8000, 10000: 12000 }

/**
 * Кольцевая жёсткость корпуса, Па — расчётная ступень 5000 или 10000.
 *
 * @param depthMm глубина подземной части корпуса, мм (≥ 0)
 * @param opts.underRoadway объект под проезжей частью — жёсткость на ступень выше
 */
export function ringStiffnessPa(depthMm: number, opts: { underRoadway?: boolean } = {}): number {
  if (!(depthMm >= 0)) {
    throw new Error('depthMm (глубина корпуса, мм) должна быть ≥ 0.')
  }
  return depthMm > SN_DEPTH_THRESHOLD_MM || opts.underRoadway ? SN_BASE.raised : SN_BASE.normal
}

/**
 * Обозначение жёсткости для заказчика: по ТТ МВК 8000 и 12000, иначе сама
 * жёсткость. Незнакомое значение возвращается как есть.
 */
export function ringStiffnessDesignation(snPa: number, opts: { mvk?: boolean } = {}): number {
  return opts.mvk ? (SN_MVK_DESIGNATION[snPa] ?? snPa) : snPa
}
