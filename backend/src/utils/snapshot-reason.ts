/**
 * Что можно делать со слепком расчёта — по причине, с которой он снят.
 *
 * До появления причины любой снапшот считался выпуском КП: печатался как
 * КП, открывал единицу для КП на проект и запрещал удалять расчёт. Слепок при
 * создании единицы (CREATE) под это не подходит: проверку строк без цены он
 * не проходил, и напечатанный по нему КП занизил бы итог «красными» строками,
 * а запрет удаления сделал бы неудаляемой каждую новую единицу.
 *
 * @module utils/snapshot-reason
 */

import type { SnapshotReason } from '@prisma/client'

/** Причины, по слепкам которых печатается КП. */
export const PRINTABLE_REASONS: readonly SnapshotReason[] = ['KP', 'MANUAL']

/**
 * По слепку можно напечатать КП.
 *
 * MANUAL остаётся печатным, как было до появления причины: ручную фиксацию
 * инженер делает осознанно, из окна «Версии», где эти же кнопки и стоят.
 */
export function isPrintable(reason: SnapshotReason): boolean {
  return PRINTABLE_REASONS.includes(reason)
}

/**
 * Слепок защищает расчёт от удаления.
 *
 * Защищают те, что подтверждают цену, ушедшую заказчику, или зафиксированы
 * инженером намеренно. Слепок создания — нет: единицу, созданную по ошибке,
 * должно быть можно удалить, как и до появления слепка.
 */
export function blocksDeletion(reason: SnapshotReason): boolean {
  return reason !== 'CREATE'
}

/** Подпись причины для людей — окно «Версии», сообщения об ошибках. */
export const REASON_LABEL: Record<SnapshotReason, string> = {
  CREATE: 'создание единицы',
  MANUAL: 'ручная фиксация',
  KP: 'выпуск КП',
}
