/**
 * Наименование изделия в КП — по образцу коммерческого отдела.
 *
 * Строка «Наименование номенклатуры» в КП устроена не так, как строка
 * расчёта: это описание поставляемого изделия, а не позиция сметы. Разбор
 * эталона — `doc/Эталон_КП_разбор.md` §5; здесь тот же шаблон в коде:
 *
 * ```
 * ⟨обозначение по проекту⟩                                   ← если задано
 * ⟨Тип изделия⟩ «НТТ» GRP ⟨марка⟩ ⟨ТУ⟩ ⟨главный параметр⟩, ⟨габариты⟩,
 * жесткость корпуса не менее SN⟨обозначение⟩, с толщиной стенки не менее ⟨t⟩ мм.
 * Изделие соответствует ⟨ТУ⟩, ГОСТ …, срок службы 50 лет. Корпус выполнен …
 * В комплекте:
 *  - ⟨узел⟩ - ⟨N⟩ шт.;
 * ```
 *
 * Чего в эталоне нет и здесь не появляется: артикулов, кодов каталога, ссылок
 * на строки расчёта, массы и объёма материалов.
 *
 * Известные части собираются, неизвестные молча опускаются: КП, где вместо
 * толщины стенки стоит «не менее null мм», хуже КП без этой характеристики.
 *
 * @module utils/kp-product
 */

/** Типы изделий калькулятора: насосная станция, ёмкость, колодец. */
export type KpDeviceType = 'KNS' | 'EMK' | 'KOL'

/** Неразрывный пробел — там, где перенос строки разорвал бы обозначение. */
const NBSP = ' '

/** Изготовитель в наименовании: «⟨тип⟩ «НТТ» GRP ⟨марка⟩». */
export const BRAND = `«НТТ»${NBSP}GRP`

/** Стандарты, на которые ссылается каждая строка изделия (эталон §5.4). */
export const GOST_LINE = 'ГОСТ Р 54560-2015 и ГОСТ Р ИСО 10467-2013'
export const SP_LINE = `СП${NBSP}32.13330.2018`
export const SERVICE_LIFE_YEARS = 50

/**
 * ТУ по типам изделий — из эталона.
 *
 * У колодца ТУ другого образца (по ОКПД2) и с другим кодом организации: это
 * не опечатка эталона, а разные документы.
 *
 * ⚠️ КНС: в эталоне так обозначена ДНС (дожимная насосная станция). Для КНС,
 * ЛНС и ДНС это одно изделие и один шаблон (ТЗ §5.6), поэтому ТУ взято то же;
 * подтверждение завода — вопрос открытый (`doc/Эталон_КП_разбор.md` §10).
 * Значение переопределяется в диалоге выпуска КП.
 */
export const TU_BY_DEVICE: Readonly<Record<KpDeviceType, string>> = {
  KNS: 'ТУ 4859-006-81652345-2019',
  EMK: 'ТУ 4859-005-81652345-2015',
  KOL: 'ТУ 22.21.21-004-99675234-2019',
}

/** Что известно об изделии к моменту печати КП. */
export interface ProductSpec {
  deviceType: KpDeviceType
  /** Тип словами: «Стеклокомпозитная канализационная насосная станция». */
  kind: string
  /** Марка изделия («СК-16,5-К 10100-2600»); пустую строка не печатает. */
  mark: string | null
  /** ТУ изделия — с приставкой «ТУ». */
  tu: string | null
  /** Главный параметр: «производительностью 25,13 л/с», «объемом V=50 м³». */
  capacity: string | null
  /** Габариты: «диаметром DN 3000 мм, высотой Hполная=11 900 мм». */
  dimensions: string | null
  /** Обозначение жёсткости для заказчика (по ТТ МВК 8000 и 12000). */
  snLabel: number | null
  /** Толщина стенки корпуса, мм. */
  wallMm: number | null
  /** Обозначение по проекту («НЕ1») — первой строкой ячейки. */
  tag: string | null
}

/** Узел комплектации: строка списка «В комплекте». */
export interface KitItem {
  name: string
  qty: number
  unit: string
}

/** Число в виде документа: запятая как разделитель дробной части, без разрядов. */
export function docNumber(value: number): string {
  return String(Number(value.toFixed(3))).replace('.', ',')
}

/**
 * Заголовочная строка изделия — первый абзац ячейки наименования.
 *
 * Части собираются в порядке эталона; отсутствующие пропускаются так, чтобы
 * не осталось ни двойных запятых, ни висящих предлогов.
 */
export function productHeadline(spec: ProductSpec): string {
  const head = [spec.kind, BRAND, spec.mark, spec.tu, spec.capacity].filter(Boolean).join(' ')

  const tail: string[] = []
  if (spec.dimensions) tail.push(spec.dimensions)
  // «Не менее» — обязательство по минимуму, а не точное значение: так в
  // эталоне у обеих характеристик корпуса.
  if (spec.snLabel != null) tail.push(`жесткость корпуса не менее SN${spec.snLabel}`)
  if (spec.wallMm != null) tail.push(`с толщиной стенки не менее ${docNumber(spec.wallMm)} мм`)

  return tail.length > 0 ? `${head}, ${tail.join(', ')}.` : `${head}.`
}

/**
 * Абзац соответствия — повторяется у каждого изделия дословно, меняется
 * только номер ТУ (эталон §5.4).
 */
export function conformityText(tu: string | null): string {
  const first = [tu, GOST_LINE].filter(Boolean).join(', ')
  return (
    `Изделие соответствует ${first}, применение стеклокомпозитных изделий ` +
    `рекомендовано техническими требованиями${NBSP}${SP_LINE}, срок службы ` +
    `стеклокомпозитного корпуса ${SERVICE_LIFE_YEARS} лет. ` +
    'Корпус выполнен методом непрерывной намотки.'
  )
}

/** Строка списка комплектации: «- Лестница из нержавеющей стали - 2 шт.;». */
export function kitLine(item: KitItem): string {
  return `- ${item.name} - ${docNumber(item.qty)} ${item.unit};`
}

/**
 * Полное наименование изделия для ячейки КП: обозначение, заголовок,
 * соответствие и комплектация — абзацами, как в эталоне.
 */
export function productDescription(spec: ProductSpec, kit: readonly KitItem[] = []): string {
  const blocks: string[] = []
  if (spec.tag) blocks.push(spec.tag)
  blocks.push(productHeadline(spec))
  blocks.push(conformityText(spec.tu))
  if (kit.length > 0) {
    blocks.push(['В комплекте:', ...kit.map(kitLine)].join('\n'))
  }
  return blocks.join('\n')
}
